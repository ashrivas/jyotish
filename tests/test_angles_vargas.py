def test_quarantined_d27_example_cannot_be_silently_used_as_a_golden_oracle():
    # The book says the 10th from Libra is Leo. Counting explicitly gives Cancer.
    # Both statements are preserved in refdata/TRIAGE.json; this is NOT an approved golden case.
    import json
    from pathlib import Path

    row = json.loads((Path(__file__).parents[1] / "refdata/TRIAGE.json").read_text())[0]
    assert row["status"] == "quarantined_pending_adjudication"
    assert row["published_sign_index"] == 4
    assert varga_sign(71, 27) == (6 + 9) % 12 == row["formula_sign_index"] == 3
    assert row["published_sign_index"] != row["formula_sign_index"]
