from hypothesis import given, strategies as st
import pytest
from app.astro.angles import classify
from app.astro.vargas import varga_sign, all_vargas
from app.astro.constants import VARGAS


@given(st.floats(min_value=0, max_value=359.999999, allow_nan=False))
def test_all_classifications_remain_in_range(longitude):
    c = classify(longitude)
    assert 0 <= c["sign_index"] < 12
    assert 0 <= c["nakshatra_index"] < 27
    assert 1 <= c["pada"] <= 4
    assert all(0 <= s < 12 for s in all_vargas(longitude).values())


@pytest.mark.parametrize("edge", [30, 60, 90, 120, 150, 180, 210, 240, 270, 300, 330])
def test_sign_edges_are_half_open_without_rounding(edge):
    assert classify(edge - 1e-8)["sign_index"] == edge // 30 - 1
    assert classify(edge)["sign_index"] == edge // 30


def test_circle_wrap_and_nakshatra_boundary():
    assert classify(360)["sign_index"] == 0
    assert classify(-1)["sign_index"] == 11
    assert classify(40 - 1e-8)["nakshatra_index"] == 2
    assert classify(40)["nakshatra_index"] == 3
    assert classify(10 - 1e-8)["pada"] == 3
    assert classify(10)["pada"] == 4


